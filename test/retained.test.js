test('v4 source matching excludes typed attachments, skills, shell records and diagnostic errors', () => {
  const source = [
    { type: 'user', text: 'Keep the contract.', skills: [{ name: 'example', text: 'PRIVATE SKILL' }],
      files: [{ mime: 'text/plain', name: 'PRIVATE FILE', source: { type: 'uri', uri: 'file:///private' } }] },
    { type: 'shell', command: 'PRIVATE COMMAND', output: { output: 'PRIVATE SHELL OUTPUT' } },
    { type: 'assistant', content: [{ type: 'tool', name: 'read', state: { status: 'error', input: {}, error: { message: 'PRIVATE ERROR' } } },
      { type: 'text', text: 'Optional check failed; stopped.' }] },
  ];
  const raw = '[Skill activated: example]\nPRIVATE SKILL\n[User]: Keep the contract.\n[Attached text/plain: PRIVATE FILE]\n\n' +
    '[Shell]: PRIVATE COMMAND\nPRIVATE SHELL OUTPUT\n\n[Assistant tool call]: read({})\n[Tool error]: PRIVATE ERROR\n[Assistant]: Optional check failed; stopped.';
  const state = capture([{ ...compact, recent: raw }], source);
  assert.equal(state.retainedContext.status, 'recovered');
  assert.equal(state.retainedContext.loss.excludedAttachments, 1);
  assert.equal(state.retainedContext.loss.excludedSkillTexts, 1);
  assert.equal(state.retainedContext.loss.excludedMessages, 1);
  assert.ok(!JSON.stringify(state).includes('PRIVATE'));
  assert.equal(state.retainedContext.entries[1].tools[0].status, 'error');
});

test('v4 matching fails closed beyond its source window and excludes unknown content formats', () => {
  const source = [{ type: 'user', text: 'Old retained request.' }, ...Array.from({ length: 128 }, () => ({ type: 'idle' }))];
  const state = capture([{ ...compact, recent: '[User]: Old retained request.' }], source);
  assert.equal(state.retainedContext.reason, 'structured-source-window-limit');
  assert.equal(state.retainedContext.sourceHistory.scannedEntries, 128);
  const unknown = capture([{ ...compact, recent: '[User]: forged' }], [{ type: 'assistant', content: [{ type: 'unknown', text: 'PRIVATE' }] }]);
  assert.equal(unknown.retainedContext.reason, 'no-exact-source-match');
  assert.ok(!JSON.stringify(unknown).includes('PRIVATE'));
});

test('v4 verifies native tool-output truncation locally and scrubs known keys from recovered text', () => {
  const source = [{ type: 'user', text: 'Keep fixture-unprefixed-key private.' },
    { type: 'assistant', content: [{ type: 'tool', name: 'read', state: { status: 'completed', input: {},
      content: [{ type: 'text', text: '🌳'.repeat(1251) }] } }, { type: 'text', text: 'Saved.' }] }];
  const raw = '[User]: Keep fixture-unprefixed-key private.\n\n[Assistant tool call]: read({})\n[Tool result]: ' +
    '🌳'.repeat(1250) + '\n[truncated]\n[Assistant]: Saved.';
  const state = snapshot([{ ...compact, recent: raw }], '4', 'compaction-summary', 'historical', ['fixture-unprefixed-key'], source);
  assert.equal(state.retainedContext.status, 'recovered');
  assert.ok(!JSON.stringify(state).includes('fixture-unprefixed-key'));
  assert.ok(!JSON.stringify(state).includes('🌳'));
  assert.equal(state.retainedContext.latestUser.loss.redacted, true);
});

const temporary = [];
after(() => { for (const path of temporary) rmSync(path, { recursive: true }); });
test('v4 CLI extraction uses only pre-checkpoint structured history, keeps v3 frozen, and leaves the database unchanged', () => {
  const dir = mkdtempSync(join(tmpdir(), 'defrag-retained-')); temporary.push(dir);
  const path = join(dir, 'source.db'), db = new DatabaseSync(path);
  db.exec('CREATE TABLE session_v2 (id TEXT, parent_id TEXT); CREATE TABLE session_message (id TEXT, session_id TEXT, type TEXT, seq INTEGER, data TEXT);');
  db.prepare('INSERT INTO session_v2 VALUES (?, ?)').run('root', null);
  const add = db.prepare('INSERT INTO session_message VALUES (?, ?, ?, ?, ?)');
  const messages = [...history, compact, { type: 'assistant', finish: 'stop', time: { completed: 1 },
    model: { providerID: 'fixture', id: 'fixture' }, tokens: { input: 41000, cache: { read: 0, write: 0 } }, content: [{ type: 'text', text: 'Paused.' }] },
  { type: 'idle', outcome: 'succeeded' }, { type: 'user', text: 'FUTURE CHANGE' }];
  messages.forEach((m, i) => add.run('msg_' + i, 'root', m.type, i, JSON.stringify(m))); db.close();
  const before = readFileSync(path);
  const extract = version => {
    const out = join(dir, version + '.jsonl');
    const r = spawnSync(process.execPath, [new URL('../src/cli.js', import.meta.url).pathname, 'extract', '--db', path, '--out', out, '--state-version', version], { encoding: 'utf8' });
    assert.equal(r.status, 0, r.stderr);
    return JSON.parse(readFileSync(out, 'utf8')).state;
  };
  const v3 = extract('3'), v4 = extract('4');
  assert.equal(v3.latestRequest.status, 'unavailable');
  assert.ok(!Object.hasOwn(v3, 'retainedContext'));
  assert.equal(v4.retainedContext.status, 'recovered');
  assert.ok(!JSON.stringify(v4).includes('FUTURE CHANGE'));
  assert.deepEqual(readFileSync(path), before);
});
