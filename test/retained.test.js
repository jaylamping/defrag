test('v4 bounds both encoded forms including recovered history and both request pins, with separate loss accounting', () => {
  const escaped = '\u0000'.repeat(7000);
  const source = [{ type: 'user', text: escaped }, ...Array.from({ length: 20 }, () => ({ type: 'assistant', content: [{ type: 'text', text: 'x'.repeat(5000) }] }))];
  const transcript = '[User]: ' + escaped + '\n\n' + source.slice(1).map(() => '[Assistant]: ' + 'x'.repeat(5000)).join('\n\n');
  const state = capture([{ ...compact, recent: transcript }, { type: 'user', text: escaped }], source);
  assert.equal(state.retainedContext.status, 'recovered');
  assert.ok(Buffer.byteLength(JSON.stringify(state)) <= 22000);
  assert.ok(Buffer.byteLength(JSON.stringify(JSON.stringify(state))) <= 22000);
  assert.equal(state.latestRequest.loss.textClipped, true);
  assert.equal(state.retainedContext.latestUser.loss.textClipped, true);
  assert.ok(state.retainedContext.loss.omittedEntries > 0);
});

